// Browsertest: online-opdatering på Firmware-siden. Kræver mock_api.py med "1".
const { chromium, devices } = require('playwright');
(async () => {
  const D = process.argv[2];
  const b = await chromium.launch();
  const fejl = [];
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
  p.on('pageerror', e => fejl.push(e.message));
  await p.goto('http://127.0.0.1:8766/');
  await p.fill('#l-kode', 'hemmelig123'); await p.click('#login-form button'); await p.waitForTimeout(800);
  await p.goto('http://127.0.0.1:8766/#firmware'); await p.waitForTimeout(600);
  console.log('Udviklerfelt er lukket fra start:', !(await p.locator('details.udvikler').getAttribute('open')));
  await p.click('#u-soeg'); await p.waitForTimeout(2500);
  console.log('Uden testversioner:', await p.locator('#u-besked').innerText());
  console.log('Installer-knap skjult:', await p.locator('#u-install').isHidden());
  await p.click('#u-test-til'); await p.waitForTimeout(2500);
  console.log('Med testversioner:', await p.locator('#u-besked').innerText());
  console.log('Knap:', await p.locator('#u-install').innerText());
  console.log('Noter vises som tekst (ingen <b>):', await p.locator('#u-noter b').count() === 0);
  await p.screenshot({ path: D + '/opd-fundet.png', fullPage: true });
  await p.click('#u-install'); await p.waitForTimeout(300);
  console.log('Dialog åben:', await p.locator('#u-dialog').evaluate(d => d.open));
  console.log('Fra/til:', await p.locator('#u-d-fra').innerText(), '->', await p.locator('#u-d-til').innerText());
  console.log('Opdatér-knap låst før bekræftelse:', await p.locator('#u-d-ja').isDisabled());
  await p.screenshot({ path: D + '/opd-dialog.png' });
  await p.click('#u-d-nej');
  console.log('Annullér lukker:', !(await p.locator('#u-dialog').evaluate(d => d.open)));
  await p.click('#u-install'); await p.check('#u-d-sikker'); await p.click('#u-d-ja');
  await p.waitForTimeout(2200);
  console.log('Under installation:', await p.locator('#u-besked').innerText());
  await p.screenshot({ path: D + '/opd-henter.png' });
  await p.waitForTimeout(4000);
  console.log('Til sidst:', await p.locator('#u-besked').innerText());
  const m = await (await b.newContext({ ...devices['iPhone 13'] })).newPage();
  await m.goto('http://127.0.0.1:8766/');
  await m.fill('#l-kode', 'hemmelig123'); await m.click('#login-form button'); await m.waitForTimeout(800);
  await m.goto('http://127.0.0.1:8766/#firmware'); await m.waitForTimeout(800);
  await m.click('#u-soeg'); await m.waitForTimeout(2500);
  await m.screenshot({ path: D + '/opd-mobil.png', fullPage: true });
  await m.click('#u-install'); await m.waitForTimeout(300);
  await m.screenshot({ path: D + '/opd-mobil-dialog.png' });
  console.log('Vandret scroll på mobil (skal være false):', await m.evaluate(() => document.documentElement.scrollWidth > innerWidth));
  console.log(fejl.length ? 'FEJL: ' + fejl.join('; ') : 'Ingen JavaScript-fejl');
  await b.close();
})();
